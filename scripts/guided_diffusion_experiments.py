"""
scripts/guided_diffusion_experiments.py  --  Part 7
Helper script for running guided-diffusion experiments on 256x256 images.

Setup (run once):
    git clone https://github.com/openai/guided-diffusion
    cd guided-diffusion && pip install -e .
    # Download model weights per data/README.md
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


GUIDED_DIFF_DIR = Path("/root/guided-diffusion")
MODEL_DIR = GUIDED_DIFF_DIR / "models"
UNCOND_MODEL = MODEL_DIR / "256x256_diffusion_uncond.pt"
CLASSIFIER_MODEL = MODEL_DIR / "256x256_classifier.pt"


def load_npz_samples(npz_path: str) -> np.ndarray:
    """Load samples from a .npz file generated by guided-diffusion.

    Returns array of shape (N, H, W, C), dtype uint8.
    """
    data = np.load(npz_path)
    key = list(data.keys())[0]
    return data[key]


def plot_grid(images: np.ndarray, ncols: int = 8, out: str = "grid.png", title: str = ""):
    """Plot images in a row and save to disk.

    Args:
        images: (N, H, W, 3) uint8 array.
        ncols:  Number of columns.
        out:    Output path.
        title:  Figure title.
    """
    N, H, W, C = images.shape
    fig, axes = plt.subplots(1, ncols, figsize=(ncols * W / 100, H / 100))
    if ncols == 1:
        axes = [axes]
    for i, ax in enumerate(axes):
        ax.imshow(images[i] if i < N else np.zeros((H, W, C), dtype=np.uint8))
        ax.axis("off")
    fig.suptitle(title)
    plt.tight_layout()
    plt.savefig(out, dpi=100, bbox_inches="tight")
    plt.close()
    print(f"Saved: {out}")


def run_sample_command(extra_args: list[str], out_dir: str, n_samples: int = 8) -> str:
    """Run the guided-diffusion image_sample.py and return the output .npz path."""
    os.makedirs(out_dir, exist_ok=True)
    cmd = [
        sys.executable,
        str(GUIDED_DIFF_DIR / "scripts" / "image_sample.py"),
        "--model_path", str(UNCOND_MODEL),
        "--image_size", "256",
        "--num_channels", "256",
        "--num_res_blocks", "2",
        "--num_heads", "4",
        "--num_heads_upsample", "-1",
        "--attention_resolutions", "32,16,8",
        "--dropout", "0.0",
        "--diffusion_steps", "1000",
        "--noise_schedule", "linear",
        "--num_samples", str(n_samples),
        "--batch_size", str(min(n_samples, 4)),
        "--use_ddim", "False",
        "--timestep_respacing", "",
        "--log_dir", out_dir,
    ] + extra_args
    subprocess.run(cmd, check=True, cwd=str(GUIDED_DIFF_DIR))
    npz_files = sorted(Path(out_dir).glob("*.npz"))
    return str(npz_files[-1])


# ------------------------------------------------------------------
# Problem 7.1  Unconditional generation
# ------------------------------------------------------------------

def plot_unconditional(npz_path: str, out: str = "7_1_unconditional.png"):
    """Plot 8 unconditionally generated 256x256 images (Problem 7.1)."""
    images = load_npz_samples(npz_path)
    plot_grid(images[:8], ncols=8, out=out, title="Unconditional Generation")


# ------------------------------------------------------------------
# Problem 7.2  Progressive generation
# ------------------------------------------------------------------

def plot_progressive(
    intermediate_npzs: list[str],
    out: str = "7_2_progressive.png",
):
    """Visualise the denoising trajectory (Problem 7.2).

    Args:
        intermediate_npzs: List of .npz paths ordered from t=T to t=0.
        out:               Output path.
    """
    frames = []
    for p in intermediate_npzs:
        imgs = load_npz_samples(p)
        frames.append(imgs[0])
    images = np.stack(frames, axis=0)
    plot_grid(images, ncols=len(frames), out=out, title="Progressive Denoising")


# ------------------------------------------------------------------
# Problem 7.3  Noise interpolation
# ------------------------------------------------------------------

def plot_noise_interpolation(npz_path: str, out: str = "7_3_interpolation.png"):
    """Plot 8 samples along a noise interpolation path (Problem 7.3)."""
    images = load_npz_samples(npz_path)
    plot_grid(images[:8], ncols=8, out=out, title="Noise Interpolation")


# ------------------------------------------------------------------
# Problem 7.4  Conditional generation
# ------------------------------------------------------------------

def plot_conditional(npz_path: str, class_labels: list[int], out: str = "7_4_conditional.png"):
    """Plot 8 class-conditional generated images (Problem 7.4)."""
    images = load_npz_samples(npz_path)
    label_str = ", ".join(str(c) for c in class_labels[:8])
    plot_grid(images[:8], ncols=8, out=out, title=f"Conditional (classes: {label_str})")


# ------------------------------------------------------------------
# Problem 7.5  Classifier scale sweep
# ------------------------------------------------------------------

def plot_classifier_scale_sweep(
    npz_paths: list[str],
    scale_values: list[float],
    out: str = "7_5_scale_sweep.png",
):
    """Plot 2 rows x N columns, one column per classifier scale (Problem 7.5).

    Args:
        npz_paths:    .npz files, one per scale value.
        scale_values: Classifier scale values (monotonically increasing).
        out:          Output path.
    """
    n = len(npz_paths)
    all_images = [load_npz_samples(p)[:2] for p in npz_paths]

    fig, axes = plt.subplots(2, n, figsize=(n * 2.56, 2 * 2.56))
    for col, (imgs, scale) in enumerate(zip(all_images, scale_values)):
        for row in range(2):
            ax = axes[row, col] if n > 1 else axes[row]
            ax.imshow(imgs[row] if row < len(imgs) else np.zeros_like(imgs[0]))
            ax.axis("off")
            if row == 0:
                ax.set_title(f"s={scale}", fontsize=8)
    plt.tight_layout()
    plt.savefig(out, dpi=100, bbox_inches="tight")
    plt.close()
    print(f"Saved: {out}")


# ------------------------------------------------------------------
# Classifier guidance sampling helper
# ------------------------------------------------------------------

def sample_with_guidance(
    guidance_scale: float,
    out_dir: str,
    n_samples: int = 8,
    class_id: int = 0,
) -> str:
    """Sample using classifier guidance at a given scale.

    Returns the path to the generated .npz file.
    """
    os.makedirs(out_dir, exist_ok=True)
    cmd = [
        sys.executable,
        str(GUIDED_DIFF_DIR / "scripts" / "classifier_sample.py"),
        "--model_path", str(UNCOND_MODEL),
        "--classifier_path", str(CLASSIFIER_MODEL),
        "--classifier_scale", str(guidance_scale),
        "--image_size", "256",
        "--num_channels", "256",
        "--num_res_blocks", "2",
        "--num_heads", "4",
        "--num_heads_upsample", "-1",
        "--attention_resolutions", "32,16,8",
        "--dropout", "0.0",
        "--diffusion_steps", "1000",
        "--noise_schedule", "linear",
        "--num_samples", str(n_samples),
        "--batch_size", str(min(n_samples, 4)),
        "--class_cond", "True",
        "--log_dir", out_dir,
    ]
    subprocess.run(cmd, check=True, cwd=str(GUIDED_DIFF_DIR))
    npz_files = sorted(Path(out_dir).glob("*.npz"))
    return str(npz_files[-1])


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--task", choices=["7_1", "7_2", "7_3", "7_4", "7_5"], required=True)
    parser.add_argument("--npz",  type=str, nargs="+", help="Path(s) to .npz file(s)")
    parser.add_argument("--out",  type=str, default=None)
    args = parser.parse_args()

    if args.task == "7_1":
        plot_unconditional(args.npz[0], out=args.out or "7_1_unconditional.png")
    elif args.task == "7_2":
        plot_progressive(args.npz, out=args.out or "7_2_progressive.png")
    elif args.task == "7_3":
        plot_noise_interpolation(args.npz[0], out=args.out or "7_3_interpolation.png")
    elif args.task == "7_4":
        plot_conditional(args.npz[0], class_labels=[], out=args.out or "7_4_conditional.png")
    elif args.task == "7_5":
        if len(args.npz) < 2:
            print("Provide at least 2 .npz files for the scale sweep.")
        else:
            scales = [0.0, 1.0, 2.0, 5.0, 10.0, 20.0, 50.0, 100.0][:len(args.npz)]
            plot_classifier_scale_sweep(args.npz, scale_values=scales, out=args.out or "7_5_scale_sweep.png")
